/* Public language API. */

export function getLanguage() {
  return getState().lang === 'ru' ? 'ru' : 'en';
}

export function isRussian() {
  return getLanguage() === 'ru';
}

export function tr(text) {
  if (!text || !isRussian()) return text;
  const key = String(text);
  return RU[key] ?? key;
}

export function languageLabel() {
  return LANGUAGES.find((language) => language.id === getLanguage())?.short ?? 'EN';
}

export function setLanguage(id) {
  const lang = id === 'ru' ? 'ru' : 'en';
  setState({ lang });
  document.documentElement.lang = lang;
  document.documentElement.dataset.lang = lang;
  return lang;
}

function translateTextNode(node) {
  const raw = node.nodeValue;
  if (!raw) return;
  const match = raw.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!match) return;
  const key = match[2];
  if (!key || !RU[key]) return;
  const translated = `${match[1]}${RU[key]}${match[3]}`;
  if (raw !== translated) node.nodeValue = translated;
}

function translateAttributes(element) {
  for (const attr of ['aria-label', 'title', 'placeholder', 'data-tip', 'alt']) {
    if (!element.hasAttribute(attr)) continue;
    const raw = element.getAttribute(attr);
    const translated = tr(raw);
    if (translated !== raw) element.setAttribute(attr, translated);
  }
}

export function localizeTree(root = document.body) {
  if (!isRussian() || !root) return;
  if (root.nodeType === Node.TEXT_NODE) {
    translateTextNode(root);
    return;
  }
  if (!(root instanceof Element) && root !== document.body) return;
  if (root instanceof Element) {
    const tag = root.tagName;
    if (['SCRIPT', 'STYLE', 'CODE', 'PRE', 'TEXTAREA'].includes(tag)) return;
    translateAttributes(root);
  }
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement;
      if (!parent) return NodeFilter.FILTER_REJECT;
      if (parent.closest('script, style, code, pre, textarea, .no-i18n')) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    },
  });
  let node = walker.nextNode();
  while (node) {
    translateTextNode(node);
    node = walker.nextNode();
  }
  if (root instanceof Element) {
    root.querySelectorAll('[aria-label], [title], [placeholder], [data-tip], [alt]').forEach(translateAttributes);
  }
}

export function startTranslator() {
  stopTranslator();
  if (!isRussian()) return;
  localizeTree(document.body);
  observer = new MutationObserver((mutations) => {
    if (!isRussian()) return;
    for (const mutation of mutations) {
      if (mutation.type === 'characterData') {
        translateTextNode(mutation.target);
      } else if (mutation.type === 'attributes') {
        translateAttributes(mutation.target);
      } else {
        mutation.addedNodes.forEach((node) => {
          if (node.nodeType === Node.TEXT_NODE) translateTextNode(node);
          else if (node.nodeType === Node.ELEMENT_NODE) localizeTree(node);
        });
      }
    }
  });
  observer.observe(document.body, {
    childList: true,
    subtree: true,
    characterData: true,
    attributes: true,
    attributeFilter: ['aria-label', 'title', 'placeholder', 'data-tip', 'alt'],
  });
}

export function stopTranslator() {
  observer?.disconnect();
  observer = null;
}

export function applyLanguage(root = document.body) {
  document.documentElement.lang = getLanguage();
  document.documentElement.dataset.lang = getLanguage();
  if (isRussian()) startTranslator();
  else stopTranslator();
  localizeTree(root);
}
